import test from 'node:test'
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'

const root = new URL('../supabase/migrations/', import.meta.url)

test('reconstructed migrations cover live schema and hardening', async () => {
  const initial = await readFile(new URL('20261029203058_initial_website_schema_rls.sql', root), 'utf8')
  const hardening = await readFile(new URL('20261029203109_tighten_function_privileges_and_indexes.sql', root), 'utf8')
  const promotion = await readFile(new URL('20261029203343_align_promotion_fields_with_api.sql', root), 'utf8')
  const grants = await readFile(new URL('20261030151610_revoke_client_table_privileges.sql', root), 'utf8')
  const reviewPermission = await readFile(new URL('20261030151715_add_review_management_permission.sql', root), 'utf8')

  for (const table of [
    'profiles', 'admin_users', 'dealer_applications', 'orders', 'quote_requests',
    'quote_request_items', 'reviews', 'review_replies', 'audit_log', 'promotions',
  ]) {
    assert.ok(initial.includes('create table public.' + table + ' '), table + ' table is defined')
    assert.ok(initial.includes('alter table public.' + table + ' enable row level security'), table + ' has RLS enabled')
  }
  assert.ok(initial.includes('order_number bigint generated by default as identity unique'))
  assert.ok(initial.includes('quote_number bigint generated by default as identity unique'))
  assert.ok(initial.includes('id bigint generated always as identity primary key'))
  assert.ok(initial.includes('create or replace function public.handle_new_user()'))
  assert.ok(initial.includes('security definer set search_path = \'\''))
  assert.ok(hardening.includes('revoke all on function public.handle_new_user() from public, anon, authenticated'))
  assert.ok(hardening.includes('create index audit_log_created_at_idx'))
  assert.ok(promotion.includes('add column if not exists max_redemptions'))
  assert.ok(promotion.includes('add column if not exists banner_text'))
  assert.ok(grants.includes('revoke all privileges on all tables in schema public from anon, authenticated'))
  assert.ok(grants.includes('alter default privileges in schema public revoke all privileges on tables from anon, authenticated'))
  assert.ok(initial.includes('can_manage_reviews boolean not null default false'))
  assert.ok(reviewPermission.includes('add column if not exists can_manage_reviews boolean not null default false'))
  assert.doesNotMatch(initial, /service_role_key/i)
})
